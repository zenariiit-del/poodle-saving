create table if not exists public.exchanges (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  local_date date not null,
  usd_amount numeric(12,2) not null check (usd_amount > 0),
  rate numeric(12,6) not null check (rate > 0),
  jpy_amount numeric(14,2) not null check (jpy_amount >= 0)
);

alter table public.exchanges enable row level security;

drop policy if exists "authenticated can read exchanges" on public.exchanges;
drop policy if exists "authenticated can insert exchanges" on public.exchanges;
drop policy if exists "authenticated can delete exchanges" on public.exchanges;

create policy "authenticated can read exchanges" on public.exchanges for select to authenticated using (true);
create policy "authenticated can insert exchanges" on public.exchanges for insert to authenticated with check (true);
create policy "authenticated can delete exchanges" on public.exchanges for delete to authenticated using (true);

grant usage on schema public to authenticated;
grant select, insert, delete on table public.exchanges to authenticated;
grant usage, select on sequence public.exchanges_id_seq to authenticated;
